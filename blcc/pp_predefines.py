# Stateful / expansion-time hooks: value supplied by pp_expand at the use
# site (R18/R19), not a stored body — these names NEVER enter the capture.
_HOOKED = {
    "__LINE__": "line", "__FILE__": "file", "__BASE_FILE__": "base",
    "__COUNTER__": "counter", "__DATE__": "date", "__TIME__": "time",
}


def _mk(name: str, params: Optional[Tuple[str, ...]], body: str) -> Macro:
    return Macro(name, tokenize(body), list(params) if params is not None
                 else None, builtin=True)


def builtins(std: str) -> Dict[str, Macro]:
    """The builtin macro table for one -std value (plan R16, full gcc 11.4
    capture per MC 12436): BASE (gnu89) -> per-std diff -> use-site hooks."""
    m: Dict[str, Macro] = {}
    for name, (params, body) in PREDEFINES_BASE.items():
        m[name] = _mk(name, params, body)
    removed: List[str]
    removed, over = PREDEFINES_STD.get(std, PREDEFINES_STD["gnu17"])
    for name in removed:
        m.pop(name, None)
    for name, (params, body) in over.items():
        m[name] = _mk(name, params, body)
    for name, kind in _HOOKED.items():
        m[name] = Macro(name, [], None, kind=kind, builtin=True)
    m["__has_attribute"] = Macro("__has_attribute", [], ["x"],
                                 kind="hasattr", builtin=True)
    m["_Pragma"] = Macro("_Pragma", [], ["x"], kind="pragma", builtin=True)
    return m
