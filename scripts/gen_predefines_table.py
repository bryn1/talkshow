"""Generate blcc/pp_predefines_data.py — the gcc-11.4-pinned predefines
table for every -std spelling blcc accepts (MC 12436, verdict-c2 F-4).

The table is pure DATA harvested from the oracle: for each spelling, run
`gcc -E -dM [-std=S] -x c /dev/null` on the pinned x86-64 LP64 Linux box,
parse every `#define`, and store the gnu89 capture as the BASE plus one
per-std DIFF (removed names + added/changed rows). Names blcc answers at
the USE SITE (__LINE__/__FILE__/__COUNTER__/__DATE__/__TIME__ — the
_HOOKED kinds in pp_predefines) and command-line macros (__KERNEL__) are
NEVER table material: the hooks must keep firing per occurrence.

Spellings gcc 11.4 itself REJECTS (c94, gnu94) alias to the iso9899:199409
capture; the driver validates the spelling list (pp_predefines.STDC_VERSIONS).

Re-run when the oracle moves:
    python3 scripts/gen_predefines_table.py > blcc/pp_predefines_data.py
Stdlib-only; same rule as scripts/gen_has_attribute_table.py (probe the
oracle, never the plan).
"""
import re
import subprocess
import sys

GCC = subprocess.run(["gcc", "--version"], capture_output=True,
                     text=True).stdout.splitlines()[0].strip()

# blcc -std spelling -> gcc -std value used for the capture; None = gcc's
# default (blcc's fallback std gnu17). c94/gnu94: gcc 11.4 rejects the
# spelling itself (measured) — alias the closest accepted capture.
CAPTURE = {
    "gnu89": "gnu89", "c89": "c89", "iso9899:1990": "iso9899:1990",
    "c94": "iso9899:199409", "gnu94": "iso9899:199409",
    "iso9899:199409": "iso9899:199409",
    "c99": "c99", "gnu99": "gnu99", "iso9899:1999": "iso9899:1999",
    "c11": "c11", "gnu11": "gnu11", "iso9899:2011": "iso9899:2011",
    "c17": "c17", "gnu17": "gnu17", "": "gnu17",
    "c2x": "c2x", "gnu2x": "gnu2x",
}

# never table material: use-site hooks (pp_predefines._HOOKED) + CLI macros
EXCLUDE = {"__LINE__", "__FILE__", "__COUNTER__", "__DATE__", "__TIME__",
           "__KERNEL__"}

_DEF = re.compile(r"^#define ([A-Za-z_][A-Za-z0-9_]*)"
                  r"(?:\(([^)]*)\))? ?(.*)$")


def capture(std):
    """One -std capture: name -> (params-tuple | None, body-string)."""
    cmd = ["gcc", "-E", "-dM", "-std=%s" % std, "-x", "c", "/dev/null"]
    out = subprocess.run(cmd, capture_output=True, text=True, check=True)
    table = {}
    for ln in out.stdout.splitlines():
        m = _DEF.match(ln)
        if not m:
            continue
        name, params, body = m.group(1), m.group(2), m.group(3).strip()
        if name in EXCLUDE:
            continue
        table[name] = (tuple(p.strip() for p in params.split(","))
                       if params is not None else None, body)
    return table


def row_lit(row):
    return "(%s, %r)" % (repr(row[0]) if row[0] is not None else "None",
                         row[1])


def main():
    base = capture(CAPTURE["gnu89"])
    lines = [
        '"""GENERATED by scripts/gen_predefines_table.py — do not hand-edit.',
        "",
        "Predefined-macro table captured from the pinned oracle on this",
        "x86-64 LP64 Linux host: %s." % GCC,
        "PREDEFINES_BASE is the `-std=gnu89` capture; PREDEFINES_STD holds",
        "one diff per -std spelling (removed names, added/changed rows).",
        "Use-site hooks (__LINE__ … __TIME__) and CLI macros (__KERNEL__)",
        "are NEVER table material — see the generator docstring.",
        '"""',
        "from __future__ import annotations",
        "",
        "GCC_ORACLE = %r" % GCC,
        "",
        "PREDEFINES_BASE = {",
    ]
    for name in sorted(base):
        lines.append("    %r: %s," % (name, row_lit(base[name])))
    lines += ["}", "", "PREDEFINES_STD = {"]
    for std, cap_std in sorted(CAPTURE.items()):
        table = capture(cap_std) if std != "gnu89" else base
        removed = tuple(sorted(set(base) - set(table)))
        changed = {n: r for n, r in table.items()
                   if base.get(n) is not None and base[n] != r}
        added = {n: r for n, r in table.items() if n not in base}
        added.update(changed)
        lines.append("    %r: (%r, {" % (std, removed))
        for name in sorted(added):
            lines.append("        %r: %s," % (name, row_lit(added[name])))
        lines.append("    }),")
    lines += ["}", ""]
    sys.stdout.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
